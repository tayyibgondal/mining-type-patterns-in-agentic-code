"""Generate the paper's LaTeX tables from pipeline output.

`table_pr_acceptance.tex` was hand-written with no generator, and that is
precisely how the draft ended up reporting 83.2% in Table 3 and 25.3% in the
RQ3 prose for the same quantity. Nothing here is transcribed by hand.

Writes into `final_figures_for_paper/`:
    table_corpus.tex      Table 1, PRs surviving each pipeline stage
    table_acceptance.tex  Table 3, merge outcome by group
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from catalogue.constructs import LANGUAGES  # noqa: E402

OUT = REPO / "final_figures_for_paper"
DATA = {
    "TypeScript": REPO / "datasets" / "typescript_data",
    "C#": REPO / "datasets" / "csharp_data",
    "Rust": REPO / "datasets" / "rust_data",
}
HUMAN_SCRAPE = {
    "TypeScript": REPO / "more_human_pr_data" / "TypeScript" / "human_ts_prs.csv",
    "C#": REPO / "more_human_pr_data" / "CSharp" / "human_csharp_prs.csv",
    "Rust": REPO / "more_human_pr_data" / "Rust" / "human_rust_prs.csv",
}
TAG = {"TypeScript": "TS", "C#": "CS", "Rust": "RS"}


def tex(name: str) -> str:
    """Language name as LaTeX. `C#` is the only one that needs escaping, and
    an unescaped `#` is a hard compile error, not a cosmetic one."""
    return name.replace("#", r"\#")


def source_totals() -> dict[tuple[str, str], int]:
    """Pre-filter PR counts, read from the sources rather than transcribed.

    These were hardcoded, which is the same failure this module exists to
    prevent. The agent side is every AIDev PR in a repository whose language
    matches and whose author is one of the five studied agents. The human side
    is every row of the scrape, which is already unique on (repo, pr_number).
    """
    from catalogue.aidev import AI_AGENTS, load_table, repos_for

    totals: dict[tuple[str, str], int] = {}
    prs = load_table("pull_request")
    for lang in DATA:
        repo_ids = set(repos_for(lang)["id"])
        sub = prs[prs["repo_id"].isin(repo_ids)]
        totals[(lang, "AI")] = int(sub["agent"].isin(AI_AGENTS).sum())
        scrape = pd.read_csv(HUMAN_SCRAPE[lang], low_memory=False,
                             usecols=["repo", "pr_number"])
        totals[(lang, "Human")] = int(
            len(scrape.drop_duplicates(subset=["repo", "pr_number"])))
    return totals


def stage_counts() -> pd.DataFrame:
    source = source_totals()
    rows = []
    for lang, d in DATA.items():
        stage2 = pd.read_parquet(d / "stage2_corpus.parquet",
                                 columns=["pr_key", "group", "merged_at",
                                          "state"])
        for group, label in (("AI", "AI Agent"), ("Human", "Human")):
            s1 = sum(
                len(pd.read_parquet(d / f"stage1_{g}.parquet",
                                    columns=["pr_key"]))
                for g in (("agent",) if group == "AI" else ("human",))
                if (d / f"stage1_{g}.parquet").exists())
            sub = stage2[stage2.group == group]
            rows.append({
                "Language": lang, "Group": label,
                "Source": "AIDev" if group == "AI" else "GitHub",
                "Original": source[(lang, group)],
                "AfterRegex": s1,
                "AfterLLM": len(sub),
            })
    return pd.DataFrame(rows)


def acceptance() -> pd.DataFrame:
    rows = []
    for lang, d in DATA.items():
        frame = pd.read_parquet(d / "stage2_corpus.parquet",
                                columns=["pr_key", "group", "merged_at",
                                         "state"])
        assert len(frame) == frame.pr_key.nunique(), f"{lang}: duplicate pr_key"
        merged = frame.merged_at.astype(str).str.len() > 4
        for group in ("AI", "Human"):
            m = frame.group == group
            n = int(m.sum())
            if not n:
                continue
            got = int((m & merged).sum())
            closed = int((m & ~merged & (frame.state == "closed")).sum())
            rows.append({
                "Language": lang, "Group": group, "N": n,
                "Merged": 100 * got / n,
                "Closed": 100 * closed / n,
                "Open": 100 * (n - got - closed) / n,
            })
    return pd.DataFrame(rows)


def write_corpus_table(counts: pd.DataFrame) -> Path:
    lines = [
        "% GENERATED by scripts/make_tables.py - do not edit by hand.",
        "\\begin{table}[!t]",
        "\\caption{Number of PRs at each filtering stage. Human PRs were "
        "collected from GitHub under the pre-Copilot criteria; agent PRs come "
        "from AIDev.}",
        "\\centering\\small",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "\\textbf{Category} & \\textbf{Source} & \\textbf{Original} & "
        "\\textbf{After Regex} & \\textbf{After LLM} & \\textbf{Kept} \\\\",
        "\\midrule",
    ]
    for lang in LANGUAGES:
        for _, r in counts[counts.Language == lang].iterrows():
            kept = 100 * r.AfterLLM / r.Original if r.Original else 0
            lines.append(
                f"{TAG[lang]}--{r.Group} & {r.Source} & {r.Original:,} & "
                f"{r.AfterRegex:,} & \\textbf{{{r.AfterLLM:,}}} & "
                f"{kept:.1f}\\% \\\\")
        if lang != LANGUAGES[-1]:
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\label{tab:dataset_size}", "\\end{table}", ""]
    dest = OUT / "table_corpus.tex"
    dest.write_text("\n".join(lines))
    return dest


def write_acceptance_table(acc: pd.DataFrame) -> Path:
    lines = [
        "% GENERATED by scripts/make_tables.py - do not edit by hand.",
        "\\begin{table*}[!t]",
        "\\caption{Pull-request acceptance in construct-related PRs. Human PRs "
        "predate the Copilot release and were found by repository search, "
        "which surfaces merged work more readily than abandoned work; see "
        "Section~\\ref{sec:threats}.}",
        "\\centering\\small",
        "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}lrrrrrr@{}}",
        "\\toprule",
        "\\multirow{2.5}{*}{\\textbf{PR Status}} & "
        + " & ".join(f"\\multicolumn{{2}}{{c}}{{\\textbf{{{tex(l)}}} (\\%)}}"
                     for l in LANGUAGES) + " \\\\",
        "\\cmidrule(lr){2-3} \\cmidrule(lr){4-5} \\cmidrule(lr){6-7}",
        " & " + " & ".join("\\textbf{AI Agent} & \\textbf{Human}"
                           for _ in LANGUAGES) + " \\\\",
        "\\midrule",
    ]
    for field, label in (("Merged", "Merged (Accepted)"),
                         ("Closed", "Closed (Rejected)"),
                         ("Open", "Open (Pending)")):
        cells = []
        for lang in LANGUAGES:
            sub = acc[acc.Language == lang].set_index("Group")
            cells += [f"{sub.loc[g, field]:.1f}" for g in ("AI", "Human")]
        lines.append(f"{label:<20} & " + " & ".join(cells) + " \\\\")
    lines.append("\\midrule")
    cells = []
    for lang in LANGUAGES:
        sub = acc[acc.Language == lang].set_index("Group")
        cells += [f"{int(sub.loc[g, 'N']):,}" for g in ("AI", "Human")]
    lines.append("Number of PRs        & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular*}",
              "\\label{tab:pr_rates}", "\\end{table*}", ""]
    dest = OUT / "table_acceptance.tex"
    dest.write_text("\n".join(lines))
    return dest


def main() -> int:
    counts = stage_counts()
    acc = acceptance()
    for path in (write_corpus_table(counts), write_acceptance_table(acc)):
        print(f"wrote {path.relative_to(REPO)}")

    print("\nCorpus:")
    print(counts.to_string(index=False))
    print("\nAcceptance (%):")
    print(acc.round(1).to_string(index=False))

    (OUT / "table_numbers.json").write_text(json.dumps(
        {"corpus": counts.to_dict("records"),
         "acceptance": acc.to_dict("records")}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
